import { test, expect } from '@playwright/test';
import { PDFDocument } from 'pdf-lib';
import { readFile } from 'node:fs/promises';
import JSZip from 'jszip';

async function source(name = 'source.pdf', width = 300) {
  const pdf = await PDFDocument.create();
  pdf.addPage([width, 400]).drawText('A document to save and share', { x: 20, y: 200, size: 12 });
  return { name, mimeType: 'application/pdf', buffer: Buffer.from(await pdf.save()) };
}

async function prepare(page, route = 'split-pdf', file) {
  await page.goto('/#/' + route);
  await page.locator('#picker').setInputFiles(file || await source());
  await page.locator('#process').click();
  await expect(page.locator('#save-options')).toBeVisible();
}

async function download(page, selector = '#download') {
  const [item] = await Promise.all([page.waitForEvent('download'), page.locator(selector).click()]);
  return { name: item.suggestedFilename(), bytes: await readFile(await item.path()) };
}

async function mockSave(page, behavior = 'success') {
  await page.addInitScript(behavior => {
    window.saveTrace = [];
    Object.defineProperty(window, 'showSaveFilePicker', {
      configurable: true,
      value: async options => {
        window.saveOptions = options;
        window.saveHadActivation = navigator.userActivation.isActive;
        if (behavior === 'cancel') throw new DOMException('Canceled', 'AbortError');
        return {
          name: 'chosen-name' + options.suggestedName.slice(options.suggestedName.lastIndexOf('.')),
          createWritable: async () => ({
            write: async file => {
              window.saveTrace.push('write');
              if (behavior === 'write-error') throw new Error('Disk full');
              window.savedBytes = [...new Uint8Array(await file.arrayBuffer())];
              window.savedName = file.name;
            },
            close: async () => { window.saveTrace.push('close'); },
            abort: async () => { window.saveTrace.push('abort'); },
          }),
        };
      },
    });
  }, behavior);
}

test('saves the renamed PDF with the native picker and actual generated bytes', async ({ page }) => {
  await mockSave(page);
  await prepare(page);
  await page.getByLabel('Save as').fill('Invoice final.pdf.pdf');
  await page.getByRole('button', { name: 'Save file', exact: true }).click();
  await expect(page.locator('#delivery-status')).toHaveText('Saved as chosen-name.pdf.');
  const saved = await page.evaluate(() => ({ options: window.saveOptions, name: window.savedName, bytes: window.savedBytes, trace: window.saveTrace, activation: window.saveHadActivation }));
  expect(saved.options.suggestedName).toBe('Invoice final.pdf');
  expect(saved.options.types[0].accept).toEqual({ 'application/pdf': ['.pdf'] });
  expect(saved.activation).toBe(true);
  expect(saved.trace).toEqual(['write', 'close']);
  expect(saved.name).toBe('Invoice final.pdf');
  const pdf = await PDFDocument.load(new Uint8Array(saved.bytes));
  expect(pdf.getPageCount()).toBe(1);
  await expect(page.getByLabel('Save as')).toHaveValue('Invoice final');
});

test('canceling Save leaves the generated file ready and starts no download', async ({ page }) => {
  await mockSave(page, 'cancel');
  let downloads = 0;
  page.on('download', () => downloads++);
  await prepare(page);
  await page.getByRole('button', { name: 'Save file', exact: true }).click();
  await expect(page.locator('#delivery-status')).toContainText('Save canceled');
  await expect(page.locator('#delivery-status')).not.toHaveClass(/error/);
  await expect(page.getByLabel('Save as')).toBeEnabled();
  await expect(page.getByRole('button', { name: 'Save file', exact: true })).toBeEnabled();
  expect(downloads).toBe(0);
  expect(await page.evaluate(() => window.saveTrace)).toEqual([]);
});

test('aborts a failed write and keeps Download available', async ({ page }) => {
  await mockSave(page, 'write-error');
  await prepare(page);
  await page.getByRole('button', { name: 'Save file', exact: true }).click();
  await expect(page.locator('#delivery-status')).toContainText('Try Download');
  expect(await page.evaluate(() => window.saveTrace)).toEqual(['write', 'abort']);
  const file = await download(page);
  expect((await PDFDocument.load(file.bytes)).getPageCount()).toBe(1);
});

for (const behavior of ['unsupported', 'throws']) {
  test(`provides a ZIP download fallback when file sharing ${behavior === 'throws' ? 'throws' : 'is unsupported'}`, async ({ page }) => {
    await page.addInitScript(behavior => {
      Object.defineProperty(window, 'showSaveFilePicker', { configurable: true, value: undefined });
      Object.defineProperty(navigator, 'canShare', { configurable: true, value: () => {
        if (behavior === 'throws') throw new Error('Unsupported policy');
        return false;
      } });
    }, behavior);
    await page.setViewportSize({ width: 320, height: 812 });
    await page.goto('/#/split-pdf');
    await page.locator('#picker').setInputFiles(await source());
    await page.getByLabel('Save each selected page separately in a ZIP').check();
    await page.locator('#process').click();
    await page.getByLabel('Save as').fill('Shared pages.zip');
    await page.getByRole('button', { name: 'Share file', exact: true }).click();
    await expect(page.getByRole('dialog', { name: 'Share your file' })).toBeVisible();
    await expect(page.locator('#share-filename')).toHaveText('Shared pages.zip');
    expect(await page.locator('#save-options').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
    const file = await download(page, '#share-download');
    expect(file.name).toBe('Shared pages.zip');
    expect(Object.keys((await JSZip.loadAsync(file.bytes)).files)).toEqual(['page-001.pdf']);
    await page.getByRole('button', { name: 'Back', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Share file', exact: true })).toBeFocused();
  });
}

test('handles share cancellation and offers a fallback after a share error', async ({ page }) => {
  await page.addInitScript(() => {
    window.shareMode = 'cancel';
    Object.defineProperty(navigator, 'canShare', { configurable: true, value: () => true });
    Object.defineProperty(navigator, 'share', { configurable: true, value: async ({ files }) => {
      window.sharedName = files[0].name;
      if (window.shareMode === 'cancel') throw new DOMException('Canceled', 'AbortError');
      throw new DOMException('Blocked', 'NotAllowedError');
    } });
  });
  await prepare(page);
  await page.getByLabel('Save as').fill('My report');
  await page.getByRole('button', { name: 'Share file', exact: true }).click();
  await expect(page.locator('#delivery-status')).toContainText('Sharing canceled');
  await expect(page.locator('#share-dialog')).not.toBeVisible();
  expect(await page.evaluate(() => window.sharedName)).toBe('My report.pdf');
  await page.evaluate(() => { window.shareMode = 'error'; });
  await page.getByRole('button', { name: 'Share file', exact: true }).click();
  await expect(page.locator('#share-dialog')).toBeVisible();
  await expect(page.locator('#share-help')).toContainText('Sharing could not open');
});

test('preserves DOCX and ZIP file types in native save requests', async ({ page }) => {
  await mockSave(page);
  for (const [route, extension, mime] of [
    ['pdf-to-word', '.docx', 'application/vnd.openxmlformats-officedocument.wordprocessingml.document'],
    ['pdf-to-images', '.zip', 'application/zip'],
  ]) {
    await prepare(page, route);
    await page.getByLabel('Save as').fill('Final copy');
    await page.getByRole('button', { name: 'Save file', exact: true }).click();
    await expect(page.locator('#delivery-status')).toContainText('Saved as');
    const saved = await page.evaluate(() => ({ options: window.saveOptions, bytes: window.savedBytes }));
    expect(saved.options.suggestedName).toBe('Final copy' + extension);
    expect(saved.options.types[0].accept).toEqual({ [mime]: [extension] });
    const zip = await JSZip.loadAsync(new Uint8Array(saved.bytes));
    if (extension === '.docx') expect(zip.file('word/document.xml')).not.toBeNull();
    else expect(zip.file('page-001.png')).not.toBeNull();
  }
});

test('a late save completion cannot overwrite the feedback for a newer result', async ({ page }) => {
  await page.addInitScript(() => {
    window.oldSaveClosed = false;
    Object.defineProperty(window, 'showSaveFilePicker', { configurable: true, value: async () => ({
      name: 'old.pdf',
      createWritable: async () => ({
        write: async file => {
          window.oldSavedBytes = [...new Uint8Array(await file.arrayBuffer())];
          await new Promise(resolve => { window.completeOldSave = resolve; });
        },
        close: async () => { window.oldSaveClosed = true; },
        abort: async () => {},
      }),
    }) });
  });
  await prepare(page, 'split-pdf', await source('old.pdf', 210));
  await page.getByRole('button', { name: 'Save file', exact: true }).click();
  await expect.poll(() => page.evaluate(() => typeof window.completeOldSave)).toBe('function');
  await page.locator('#picker').setInputFiles(await source('new.pdf', 320));
  await page.locator('#process').click();
  await expect(page.getByLabel('Save as')).toBeVisible();
  await page.evaluate(() => window.completeOldSave());
  await expect.poll(() => page.evaluate(() => window.oldSaveClosed)).toBe(true);
  await expect(page.locator('#delivery-status')).toBeEmpty();
  const current = await download(page);
  expect((await PDFDocument.load(current.bytes)).getPage(0).getWidth()).toBe(320);
  const oldBytes = await page.evaluate(() => window.oldSavedBytes);
  expect((await PDFDocument.load(new Uint8Array(oldBytes))).getPage(0).getWidth()).toBe(210);
});
